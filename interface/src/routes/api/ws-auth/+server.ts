/**
 * Answers the bridge's WebSocket challenge for the page.
 *
 * The bridge gates `ws://…:8081` behind an HMAC challenge (see
 * `interface/bridge/utils/wsSecret.js`), which means the browser needs
 * the secret to answer. The secret lives in a machine-local file that
 * only server-side code can read, so this route signs the page's salt
 * with it — both processes run on the same machine and share the file.
 *
 * **What this is worth, stated plainly.** Anything that can reach this
 * route can get a proof, and this route is served on the same
 * LAN as the WebSocket. So the gate raises the bar from "anything that
 * can reach port 8081" to "anything that can load the app" — it stops
 * stray clients, stale tabs from another machine and port scanners,
 * not a determined attacker already on the network. Pairing (ADR-491)
 * closes that gap: `hooks.server.ts` lets this route answer only the Mac
 * itself (Vamp for iPad over the cable included) and paired devices.
 *
 * Never cached: the secret can be regenerated by deleting the file, and
 * a client holding a stale copy would fail the challenge with no way to
 * recover short of a hard reload.
 */

import { error, json, type RequestHandler } from '@sveltejs/kit';
import { createHmac } from 'node:crypto';
import { resolveSecret } from '$lib/server/wsSecret';

/**
 * `GET /api/ws-auth?salt=<hex>` → `{ proof }`.
 *
 * The proof is HMAC-SHA256(secret, salt), hex — byte-identical to what
 * `interface/bridge/utils/wsSecret.js` computes, because it is the same
 * three lines of `node:crypto`.
 *
 * **Why the server does this and not the page.** The page used to
 * compute it with `crypto.subtle`, which only exists in a *secure
 * context*. Browsers grant that to `https://` and to `http://localhost`
 * but not to a bare IP — so the iPad, which reaches this rig at
 * `http://169.254.216.140:8889` over USB-C or `http://10.43.156.117:8889`
 * over WiFi, could never answer the challenge. It connected, stayed
 * silent, and the bridge (correctly) told it nothing, which surfaced as
 * "No tracks in session" against a healthy Live set.
 *
 * The salt is required. A salt-less request used to return the raw
 * secret, for pages cached before the proof existed; nothing asked for it
 * any more, and it handed the secret to anyone who did (2026-09-30).
 */
export const GET: RequestHandler = async ({ url }) => {
	let secret: string | null;
	try {
		secret = resolveSecret();
	} catch (e) {
		throw error(500, `Could not read the WebSocket secret: ${(e as Error).message}`);
	}

	if (!secret) {
		// The bridge generates this on first run, so "missing" means the
		// bridge has never started — the UI has nothing to connect to
		// either way, and saying so beats a silent auth failure.
		throw error(503, 'WebSocket secret not available — has the bridge started?');
	}

	// The bridge's salt is hex from `crypto.randomBytes`. Rejecting
	// anything else keeps this from being a general-purpose HMAC oracle
	// over caller-chosen input.
	const salt = url.searchParams.get('salt');
	if (salt === null || !/^[0-9a-f]{16,128}$/.test(salt)) {
		throw error(400, 'salt must be 16-128 lowercase hex characters');
	}
	const proof = createHmac('sha256', secret).update(salt).digest('hex');
	return json({ proof }, { headers: { 'cache-control': 'no-store' } });
};
