import { describe, expect, it } from 'vitest';
import { variationNamesOf } from '$lib/server/rackVariations';

const snapshot = (id: number, name: string) =>
	`<MacroSnapshot Id="${id}"><AutogeneratedNameIndex Value="0" /><SnapshotName Value="${name}" /><MacroValues.0 Value="1" /></MacroSnapshot>`;

describe('variationNamesOf (ADR-531)', () => {
	it('reads each variation name, in order, from a rack file', () => {
		const xml = `<Rack><MacroVariations><MacroSnapshots>${snapshot(0, 'Boombox')}${snapshot(1, 'Cheap Unit')}${snapshot(2, 'Push &amp; Punch')}</MacroSnapshots></MacroVariations></Rack>`;
		expect(variationNamesOf(xml)).toEqual(['Boombox', 'Cheap Unit', 'Push & Punch']);
	});
	it('reads none from a rack with no variations', () => {
		expect(variationNamesOf('<Rack><MacroVariations><MacroSnapshots /></MacroVariations></Rack>')).toEqual([]);
		expect(variationNamesOf('<Rack />')).toEqual([]);
	});
	it('keeps an unnamed variation as an empty name, so the count still matches', () => {
		const xml = `<MacroVariations>${snapshot(0, 'A')}<MacroSnapshot Id="1"><MacroValues.0 Value="1" /></MacroSnapshot></MacroVariations>`;
		expect(variationNamesOf(xml)).toEqual(['A', '']);
	});
});
